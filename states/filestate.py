from __future__ import annotations
from typing import Dict, TypedDict, Literal, Optional


class ColumnStats(TypedDict, total=False):
    """Statistics for a single column in a sheet."""
 
    # Number of non-null rows in this column
    non_null_count: int
    # Number of unique values in this column
    unique_count: int    
    

class ColumnMeta(TypedDict, total=False):
    """Metadata for a single column in a sheet."""

    # Column name
    name: str
    # Pandas / Python dtype as string (e.g. "int64", "float64", "object")
    dtype: str
    # Optional statistics for this column
    stats: ColumnStats


class SheetMeta(TypedDict, total=False):
    """Metadata for a single sheet in a workbook."""

    # Optional: you can store a serialized representation of the df
    # (e.g. parquet path, JSON preview, etc.). Keeping type flexible.
    df_ref: Optional[str]

    # Row statistics
    row_count: int

    # Column collection and overall stats
    columns: Dict[str, ColumnMeta]

   # Optional natural-language summary generated by the LLM
    sheet_summary: Optional[str]


class FileMeta(TypedDict, total=False):
    """Metadata for a single file (workbook) for this session."""

    # Absolute or relative path to the file
    path: str

    # Whether this is an input or output file
    io_type: Literal["input", "output"]

    # All sheets inside the workbook, keyed by sheet name
    sheets: Dict[str, SheetMeta]


class FileState(TypedDict, total=False):
    """File state for a *single* session/call.

    JSON-of-JSON example:
    {
        "input_files": {
            "sales_customers.xlsx": {
                "path": "data/input_files/<session_id>/sales_customers.xlsx",
                "io_type": "input",
                "sheets": {
                    "Sheet1": {
                        "row_count": 100,
                        "columns": {
                            "customer_id": {
                                "name": "customer_id",
                                "dtype": "int64",
                                "stats": {
                                    "non_null_count": 100,
                                    "unique_count": 100                                   
                                }
                            }
                        }
                        "summary":"sheet contains so and so details"
                    }
                }
            }
        },
        "output_files": {
            "sales_output_kpis.xlsx": {
                "path": "data/output_files/<session_id>/sales_output_kpis.xlsx",
                "io_type": "output",
                "sheets": { /* same structure as above */ }
            }
        }
    }
    """

    # All input files for this session, keyed by filename
    input_files: Dict[str, FileMeta]

    # All output files for this session, keyed by filename
    output_files: Dict[str, FileMeta]